#!/usr/bin/env python3
"""Harvest precise public still-camera entries from Webcam Galore country/detail pages."""
import requests,re,html,json,concurrent.futures,unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]; OUT=ROOT/'lib/cameras.webcamgalore.generated.ts'
CACHE=Path('/tmp/webcamgalore-camera-cache.json'); cache=json.loads(CACHE.read_text()) if CACHE.exists() else {}
S=requests.Session();S.headers.update({'User-Agent':'Mozilla/5.0 elsewhere-discovery-research'})
def norm(x):return re.sub(r'[^a-z0-9]+',' ',unicodedata.normalize('NFKD',x or '').encode('ascii','ignore').decode().lower()).strip()
def get(url):
    if url in cache and cache[url]:return cache[url]
    try:
        r=S.get(url,timeout=16);text=r.text if r.ok else ''
    except Exception:text=''
    if text:cache[url]=text
    return text
def infer(title):
    t=norm(title)
    if 'volcano' in t:return 'volcano'
    if 'aurora' in t or 'northern lights' in t:return 'aurora'
    if any(x in t for x in ['animal','wildlife','safari','waterhole']):return 'wildlife'
    if any(x in t for x in ['beach','harbour','harbor','port','sea','ocean','lake','river','canal','bay','marina','coast','island']):return 'water'
    if any(x in t for x in ['mountain','alps','desert','park','panorama','valley','glacier','ski']):return 'nature'
    return 'city'
def detail(url):
    text=get(url)
    if not text:return None
    lat=re.search(r'og:latitude" content="(-?[\d.]+)',text)
    lon=re.search(r'og:longitude" content="(-?[\d.]+)',text)
    img=re.search(r'https://images\.webcamgalore\.com/\d+-current-webcam-[^"\'<> ]+?\.jpg',text)
    title=re.search(r'<title>(.*?)</title>',text,re.S)
    if not (lat and lon and img and title):return None
    title=html.unescape(title.group(1)).replace(' - Webcam Galore','').strip()
    place=title.replace('Webcam ','').strip()
    return {'title':'Webcam '+place if not title.lower().startswith('webcam') else title,'place':place,'lat':float(lat.group(1)),'lon':float(lon.group(1)),'image':img.group(0),'sourceUrl':url}
def main():
    countries=[c for c in requests.get('https://raw.githubusercontent.com/mledoze/countries/master/countries.json',timeout=25).json() if c.get('independent')]
    byname={norm(c['name']['common']):c for c in countries}
    aliases={'czech republic':'czechia','macedonia':'north macedonia','cape verde':'cabo verde','turkey':'turkiye'}
    covered=set()
    for f in ['lib/cameras.ts','lib/cameras.generated.ts','lib/cameras.skyline.generated.ts']:
        covered.update(re.findall(r"country: '([^']+)'",(ROOT/f).read_text()))
    index=get('https://www.webcamgalore.com/')
    targets=[];seen=set()
    for href,slug,name in re.findall(r'href="(/([^"/]+)/countrycam-0\.html)"[^>]*>(.*?)</a>',index):
        key=norm(html.unescape(name));lookup=aliases.get(key,key);c=byname.get(lookup)
        if not c or c['name']['common'] in covered or slug in seen:continue
        seen.add(slug);targets.append((c,html.unescape(name),'https://www.webcamgalore.com'+href))
    jobs=[]
    for c,name,url in targets:
        page=get(url)
        links=[]
        for link in re.findall(r'https://www\.webcamgalore\.com/webcam/[^"<>]+?\.html',page):
            if link not in links:links.append(link)
        for link in links[:4]:jobs.append((c,link))
    print('webcamgalore target countries',len(targets),'detail candidates',len(jobs),flush=True)
    final=[]
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as ex:
        futs={ex.submit(detail,url):(c,url) for c,url in jobs}
        for fut in concurrent.futures.as_completed(futs):
            c,url=futs[fut];d=fut.result()
            if not d:continue
            d['country']=c['name']['common'];d['cca2']=c['cca2'].lower();final.append(d)
    grouped={}
    for x in final:grouped.setdefault(x['country'],[]).append(x)
    rows=[]
    for country,items in grouped.items():
        for rank,x in enumerate(items[:2],1):
            x['id']=f"wcg-{x['cca2']}-{rank}";rows.append(x)
    lines=['// Generated by tools/generate_webcamgalore_cameras.py from public Webcam Galore camera pages.','import type { PublicCamera } from "./cameras";','','export const webcamGaloreCameras: PublicCamera[] = [']
    for x in sorted(rows,key=lambda z:(z['country'],z['id'])):
        q=lambda s:str(s).replace('\\',' ').replace("'","\\'")
        lines.append("  { id: '%s', title: '%s', lat: %s, lon: %s, stillImage: '%s', sourceUrl: '%s', place: '%s', kind: '%s', quality: 76, country: '%s', confidence: 'medium', approximate: true, sourceName: 'Webcam Galore' },"%(x['id'],q(x['title']),round(x['lat'],5),round(x['lon'],5),x['image'],x['sourceUrl'],q(x['place']+', '+x['country']),infer(x['title']),q(x['country'])))
    lines.append('];\n');OUT.write_text('\n'.join(lines));CACHE.write_text(json.dumps(cache))
    print('GENERATED webcamgalore entries',len(rows),'countries',len(grouped),'file',OUT)
if __name__=='__main__':main()
